// Writes docs/ops/dashboard-v2-uk-names-review.md (entities part, V47). Usage: node scripts/names-review-sheet.mjs
import {readFileSync, writeFileSync} from "node:fs";
import {dirname, join} from "node:path";
import {fileURLToPath} from "node:url";
import {proposeName} from "../src/lib/names-uk.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const fixture = JSON.parse(readFileSync(join(root, "site/tests/fixtures/v2_export/meta/entities.json"), "utf8")).entities;
const cfg = (f) => readFileSync(join(root, f), "utf8").split("\n");
const rows = []; // {section, id, kind, en, where}
const ents = new Map();
for (const l of cfg("config/entities.yaml")) {
  const m = l.match(/\{id: (\w+), name: ([^,]+), kind: (\w+)/);
  if (m) ents.set(m[1], {section: "entities", id: m[1], en: m[2].trim(), kind: m[3], where: "config/entities.yaml"});
}
for (const e of fixture) if (!ents.has(e.entity_id)) ents.set(e.entity_id, {section: "entities", id: e.entity_id, en: e.name, kind: e.kind, where: "fixture only"});
const inds = cfg("config/indicators.yaml");
for (const l of inds) {
  const m = l.match(/^  - \{id: (\w+), name: ([^,}]+)/);
  if (m) rows.push({section: "domains", id: m[1], kind: "domain", en: m[2].trim(), where: "config/indicators.yaml"});
}
for (let i = 0; i < inds.length; i++) {
  const m = inds[i].match(/^  - id: (\w+)/);
  const n = m && inds[i + 1].match(/^    name: (.+)$/);
  if (n) rows.push({section: "indicators", id: m[1], kind: "indicator", en: n[1].trim(), where: "config/indicators.yaml"});
}
const srcLines = cfg("config/sources.yaml");
for (let i = 0; i < srcLines.length; i++) {
  const m = srcLines[i].match(/^  - id: (\w+)/);
  const n = m && srcLines[i + 1].match(/^    name: (.+)$/);
  if (n) rows.push({section: "sources", id: m[1], kind: "source", en: n[1].trim().replace(/^["']|["']$/g, ""), where: "config/sources.yaml"});
}
rows.push(...ents.values());
let dn = null;
try { dn = new Intl.DisplayNames(["uk"], {type: "region"}); } catch {}
// Only entities get a proposal (Intl / hand). Domains, indicators and sources stay empty: no agent translation of economic terms (same rule as the string sheet).
const prop = (r) => (r.section === "entities" ? proposeName(r.id, dn, r.en) : {uk: "", source: "none", status: "proposed"});
const out = rows.map((r, i) => `| ${i + 1} | ${r.section} | \`${r.id}\` | ${r.kind} | ${r.en.replace(/\|/g, "/")} | ${prop(r).uk} | ${prop(r).source} | proposed |  |  | ${r.where} |`);
const miss = rows.filter((r) => r.section === "entities" && prop(r).uk === "").map((r) => r.id);
const doc = `# Ukrainian entity names review sheet (V47, G-LANG-STR) - DRAFT

Generated by \`site/scripts/names-review-sheet.mjs\`. Not approved. Every row is \`proposed\`; only the user (or a reviewer the user names) may change a row to \`reviewed\`. Until then the site shows the English name inside \`lang="en"\` (\`site/src/lib/names-uk.js\`, \`resolveName\`).

Scope: domains, indicators and sources (English names from \`config/*.yaml\`; Ukrainian left empty on purpose, no agent translation) and entities (42 panel countries + EU27, EA, WLD, plus fixture-only UKR and NOR; proposals below). Source rows use the config id; the export keys sources by stored \`source_name\`, so that mapping is open before sources reach \`names.uk.json\`.

How to review: edit the Ukrainian column; to accept a row set Status to \`reviewed\` and fill Reviewer and Reviewed on (YYYY-MM-DD). \`site/scripts/names-import.mjs\` rejects a \`reviewed\` row without Ukrainian text, a reviewer and a date, and imports nothing else.

Source column: \`intl\` = \`Intl.DisplayNames(['uk'], {type: 'region'})\` via the static ISO3-to-ISO2 table; \`hand\` = hand proposal (aggregates are never sent through Intl: ISO2 "EA" is Ceuta and Melilla); \`none\` = nothing proposed.

ICU state on the generating Node (${process.version}, ICU ${process.versions.icu}): Intl.DisplayNames supports "uk": ${Intl.DisplayNames.supportedLocalesOf(["uk"]).length > 0}. Misses (empty proposal): ${miss.length ? miss.join(", ") : "none"}.
Node 20 ICU (the pinned build, OQ-21): [UNVERIFIED] here; only Node ${process.version} was available. Official Node 20 builds ship full ICU, but the unit test must be run on the CI Node 20 to confirm.

| # | Section | ID | Kind | English | Ukrainian (proposed) | Source | Status | Reviewer | Reviewed on | Listed in |
|---|---|---|---|---|---|---|---|---|---|---|
${out.join("\n")}
`;
writeFileSync(join(root, "docs/ops/dashboard-v2-uk-names-review.md"), doc);
console.log(`${rows.length} rows, misses: ${miss.join(",") || "none"}`);
