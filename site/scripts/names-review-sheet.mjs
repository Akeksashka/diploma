// Writes docs/ops/dashboard-v2-uk-names-review.md (entities part, V47). Usage: node scripts/names-review-sheet.mjs
import {readFileSync, writeFileSync} from "node:fs";
import {dirname, join} from "node:path";
import {fileURLToPath} from "node:url";
import {proposeName} from "../src/lib/names-uk.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const fixture = JSON.parse(readFileSync(join(root, "site/tests/fixtures/v2_export/meta/entities.json"), "utf8")).entities;
const rows = new Map();
for (const l of readFileSync(join(root, "config/entities.yaml"), "utf8").split("\n")) {
  const m = l.match(/\{id: (\w+), name: ([^,]+), kind: (\w+)/);
  if (m) rows.set(m[1], {id: m[1], en: m[2].trim(), kind: m[3], where: "config/entities.yaml"});
}
for (const e of fixture) if (!rows.has(e.entity_id)) rows.set(e.entity_id, {id: e.entity_id, en: e.name, kind: e.kind, where: "fixture only"});
let dn = null;
try { dn = new Intl.DisplayNames(["uk"], {type: "region"}); } catch {}
const out = [...rows.values()].map((r, i) => {
  const p = proposeName(r.id, dn, r.en);
  return `| ${i + 1} | \`${r.id}\` | ${r.kind} | ${r.en} | ${p.uk} | ${p.source} | proposed | ${r.where} |`;
});
const miss = [...rows.values()].filter((r) => proposeName(r.id, dn, r.en).uk === "").map((r) => r.id);
const doc = `# Ukrainian entity names review sheet (V47, G-LANG-STR) - DRAFT

Generated by \`site/scripts/names-review-sheet.mjs\`. Not approved. Every row is \`proposed\`; only the user (or a reviewer the user names) may change a row to \`reviewed\`. Until then the site shows the English name inside \`lang="en"\` (\`site/src/lib/names-uk.js\`, \`resolveName\`).

Scope of this sheet: entities (42 panel countries + EU27, EA, WLD from \`config/entities.yaml\`, plus fixture-only UKR and NOR). Domains, indicators and sources are not in this sheet yet (they belong to V44/V46 dictionaries).

Source column: \`intl\` = \`Intl.DisplayNames(['uk'], {type: 'region'})\` via the static ISO3-to-ISO2 table; \`hand\` = hand proposal (aggregates are never sent through Intl: ISO2 "EA" is Ceuta and Melilla); \`none\` = nothing proposed.

ICU state on the generating Node (${process.version}, ICU ${process.versions.icu}): Intl.DisplayNames supports "uk": ${Intl.DisplayNames.supportedLocalesOf(["uk"]).length > 0}. Misses (empty proposal): ${miss.length ? miss.join(", ") : "none"}.
Node 20 ICU (the pinned build, OQ-21): [UNVERIFIED] here; only Node ${process.version} was available. Official Node 20 builds ship full ICU, but the unit test must be run on the CI Node 20 to confirm.

| # | Entity | Kind | English | Ukrainian (proposed) | Source | Status | Listed in |
|---|---|---|---|---|---|---|---|
${out.join("\n")}
`;
writeFileSync(join(root, "docs/ops/dashboard-v2-uk-names-review.md"), doc);
console.log(`${rows.size} rows, misses: ${miss.join(",") || "none"}`);
