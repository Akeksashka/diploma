// V44: writes src/i18n/dictionaries.js from src/i18n/{en,uk}.json. Framework 1.13.4 cannot bundle `import ... with {type: "json"}` (its parser stops at `with`),
// so the browser-side lib/i18n.js imports this generated plain module; the JSON files stay the single source (reviewers and tests read them).
// Usage: node scripts/prepare-i18n.mjs [--check]. --check fails when the committed module differs from the JSON files (the i18n-parity test runs it).
import {readFileSync, writeFileSync} from "node:fs";
import {dirname, join} from "node:path";
import {fileURLToPath} from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, "..", "src", "i18n");
const read = (n) => JSON.parse(readFileSync(join(dir, n), "utf8"));

export function dictionariesSource() {
  const body = JSON.stringify({en: read("en.json"), uk: read("uk.json")}, null, 1); // one property per line: line-based source scans see one entry at a time
  return `// GENERATED by scripts/prepare-i18n.mjs from en.json and uk.json: do not edit. Run \`npm run prepare-i18n\`.\nexport const dictionaries = ${body};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = join(dir, "dictionaries.js");
  const next = dictionariesSource();
  if (process.argv.includes("--check")) {
    let cur = "";
    try { cur = readFileSync(target, "utf8"); } catch { /* missing */ }
    if (cur !== next) { console.error("prepare-i18n: src/i18n/dictionaries.js is out of date; run npm run prepare-i18n"); process.exit(1); }
    console.log("prepare-i18n: dictionaries.js is in sync");
  } else {
    writeFileSync(target, next);
    console.log("prepare-i18n: wrote src/i18n/dictionaries.js");
  }
}
